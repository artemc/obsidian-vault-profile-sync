const dict: Record<Key, string> = getLanguage().toLowerCase().startsWith("ru") ? ru : en;

export function t(key: Key, vars: Record<string, string | number> = {}): string {
	return dict[key].replace(/\{(\w+)\}/g, (_, v: string) => String(vars[v] ?? ""));
}

export function has(key: string): key is Key {
	return key in dict;
}
